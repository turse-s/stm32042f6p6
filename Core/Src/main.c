float NTC_GetTemp(uint16_t adc_val)
{
    float voltage = adc_val * 3.3f / 4095.0f;
    float Rt = 100000.0f * (3.3f - voltage) / voltage;
    float temp;
    temp = 1.0f / (1.0f / 298.15f + log(Rt / 100000.0f) / 3950.0f);
    temp = temp - 273.15f;
    return temp;
}

