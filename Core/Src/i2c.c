/******************************************************************************
* @brief  i2c memory read
* @param  *hi2c: i2c handle
*         dev_addr: device address
*         mem_addr: memory address
*         mem_addr_size: memory address size @ref eI2cMemAddrSize
*         *buf: buffer
*         size: size
* @retval 0: ok; other: err;
*******************************************************************************/
int i2cMemRead(I2C_HandleTypeDef *hi2c, unsigned short devAddr, unsigned int memAddr, eI2cMemAddrSize memAddrSize, unsigned char *buf, unsigned short size)
{
    int err = 0;

    err = HAL_I2C_Mem_Read(hi2c, devAddr, memAddr, memAddrSize, buf, size, 500);
    if (0 != err) {
        err = HAL_I2C_DeInit(hi2c);
        err = HAL_I2C_Init(hi2c);
    }

    return err;
}

